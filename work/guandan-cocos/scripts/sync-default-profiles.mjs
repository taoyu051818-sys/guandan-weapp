// Generated catalog and bundled pixels keep all avatar requests off third-party domains at runtime.
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
const source = new URL('../../guandan-windows-source/server/data/default-profiles/', import.meta.url)
const target = new URL('../assets/game-assets/ui/profiles/', import.meta.url)
const catalog = JSON.parse(readFileSync(new URL('catalog.json', source), 'utf8'))
mkdirSync(target, { recursive: true })
const canonicalByHash = new Map()
const profiles = catalog.profiles.map(({ displayName, avatarUrl, file }) => {
  const hash = createHash('sha256').update(readFileSync(new URL(file, source))).digest('hex')
  let canonical = canonicalByHash.get(hash)
  if (!canonical) {
    canonical = file
    canonicalByHash.set(hash, canonical)
    copyFileSync(new URL(file, source), new URL(file, target))
  }
  return { displayName, avatarUrl, asset: `ui/profiles/${canonical.replace(/\.[^.]+$/, '')}/texture` }
})
writeFileSync(new URL('../assets/scripts/services/DefaultProfileCatalog.ts', import.meta.url),
  '// Generated by scripts/sync-default-profiles.mjs. Do not hand edit.\nexport const DEFAULT_PROFILE_CATALOG = ' + JSON.stringify(profiles, null, 2) + ' as const\n')
console.log(`Synced ${profiles.length} default profiles`)
