const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const projectRoot = path.resolve(__dirname, '..')
const developmentApis = fs.readFileSync(path.join(projectRoot, 'migration/platform/RetiredDevelopmentApis.ts'), 'utf8')
const gatewayContracts = fs.readFileSync(path.join(projectRoot, 'assets/scripts/services/FrontPageGatewayContracts.ts'), 'utf8')
const platformFacade = fs.readFileSync(path.join(projectRoot, 'assets/scripts/services/PlatformApi.ts'), 'utf8')
const merchantGateway = fs.readFileSync(path.join(projectRoot, 'migration/platform/merchantGateway.ts'), 'utf8')
const frontPages = fs.readFileSync(path.join(projectRoot, 'assets/scripts/scenes/FrontPageController.ts'), 'utf8')
const merchantPages = fs.readFileSync(path.join(projectRoot, 'migration/merchant/MerchantPageDomain.ts'), 'utf8')
const pageRouter = fs.readFileSync(path.join(projectRoot, 'assets/scripts/scenes/PageRouter.ts'), 'utf8')
const uiFactory = fs.readFileSync(path.join(projectRoot, 'assets/scripts/ui/RuntimeUiFactory.ts'), 'utf8')

assert.match(gatewayContracts, /export interface MerchantGateway/)
assert.match(gatewayContracts, /getConsole\(\): Promise<MerchantConsole>/)
assert.match(gatewayContracts, /apply\(application: MerchantApplication\): Promise<MerchantProfile>/)
assert.match(gatewayContracts, /createStore\(store: MerchantStoreDraft\): Promise<MerchantStore>/)
assert.match(gatewayContracts, /addEmployee\(employee: MerchantEmployeeDraft\): Promise<MerchantEmployee>/)
assert.match(gatewayContracts, /grantPoints\(grant: MerchantPointGrantDraft\): Promise<MerchantPointGrant>/)
assert.match(developmentApis, /SAMPLE_MERCHANT_CONSOLE/)
assert.match(developmentApis, /陵水生活馆（演示）/)
assert.match(developmentApis, /DevelopmentMerchantGateway[\s\S]*getConsole[\s\S]*SAMPLE_MERCHANT_CONSOLE/)
for (const method of ['apply', 'createStore', 'addEmployee', 'grantPoints']) {
  assert.match(developmentApis, new RegExp(`public async ${method} \\([^)]*\\): Promise<[^>]+> \\{ throw new FeatureInDevelopmentError`), `development ${method} must stay read-only`)
}

for (const route of ['/api/v1/merchants/apply', '/api/v1/merchants/me', '/api/v1/merchants/stores', '/api/v1/merchants/employees', '/api/v1/merchants/points/grant']) {
  assert.match(merchantGateway, new RegExp(route.replaceAll('/', '\\/')), `missing merchant route ${route}`)
}
assert.match(platformFacade, /export \{ createHttpGateways \} from '\.\/platform\/factory'/, 'the public PlatformApi import must remain a compatibility facade')
assert.doesNotMatch(platformFacade, /class HttpMerchantGateway/, 'merchant implementation must not leak back into the public facade')
assert.match(merchantGateway, /class HttpMerchantGateway implements MerchantGateway/)
assert.match(merchantGateway, /uncertainMutationKeys = new Map<string, string>/)
assert.match(merchantGateway, /'Idempotency-Key': key/g)
assert.match(merchantGateway, /normalizeMerchantConsole/)
assert.match(merchantGateway, /商户后台响应包含其他商户的数据/)
assert.match(merchantGateway, /INVALID_MERCHANT_INPUT/)

assert.doesNotMatch(frontPages, /移动端管理界面开发中/)
assert.doesNotMatch(frontPages, /showMerchantConsole|MerchantPageDomain/, 'the ordinary player shell must not expose the dormant merchant migration surface')
assert.equal(fs.existsSync(path.join(projectRoot, 'assets/scripts/scenes/front-pages/MerchantPageDomain.ts')), false, 'dormant merchant UI must stay outside the Cocos bundle')
assert.match(merchantPages, /export class MerchantPageDomain/)
assert.match(merchantPages, /this\.dependencies\.gateways\.merchant\.getConsole\(\)/)
assert.match(merchantPages, /error instanceof PlatformApiError && error\.status === 403/)
assert.match(merchantPages, /renderApplication\('当前账号没有商户权限/)
assert.match(merchantPages, /只读演示 · 未连接平台服务 · 不会提交任何写入/)
assert.match(merchantPages, /if \(!this\.dependencies\.gateways\.configured\)[\s\S]*写入按钮仅在已配置平台/)
assert.match(merchantPages, /merchantConsole\.merchant\.status !== 'active'/)
assert.match(merchantPages, /merchantConsole\.role === 'owner' \|\| merchantConsole\.role === 'manager'/)
assert.match(merchantPages, /merchantConsole\.role === 'owner'/)
assert.match(merchantPages, /this\.dependencies\.gateways\.merchant\.apply\(\{ name, contactName \}\)/)
assert.match(merchantPages, /this\.dependencies\.gateways\.merchant\.createStore\(\{ name, address \}\)/)
assert.match(merchantPages, /this\.dependencies\.gateways\.merchant\.addEmployee\(\{ employeeUserId, role \}\)/)
assert.match(merchantPages, /this\.dependencies\.gateways\.merchant\.grantPoints\(\{ storeId, recipientUserId, amount, note \}\)/)
assert.match(merchantPages, /pendingAction/)
for (const page of ['merchant-apply', 'merchant-store', 'merchant-employee', 'merchant-grant']) {
  assert.match(merchantPages, new RegExp(`isCurrent\\(pageToken, '${page}'\\)`), `${page} must ignore late write responses`)
  assert.doesNotMatch(pageRouter, new RegExp(`'${page}'`), `${page} must stay outside the player router`)
}
assert.match(merchantPages, /private isCurrent[\s\S]*currentPageRequest\(\)[\s\S]*router\.current === page/, 'merchant writes must share one route-aware late-response guard')
assert.match(merchantPages, /MerchantGrantRecipientInput/)
assert.match(merchantPages, /Number\(amountInput\.string\.trim\(\)\)/)
assert.doesNotMatch(merchantPages, /recipientUserId:\s*['"][^'"]+['"]/, 'merchant UI must never submit a fixed recipient account')

assert.match(uiFactory, /public formInput \(/)
assert.match(uiFactory, /options\.inputMode \?\? EditBox\.InputMode\.ANY/)
assert.match(uiFactory, /options\.initialValue \?\? ''/)
assert.equal(uiFactory.indexOf("new Node('TEXT_LABEL')") < uiFactory.indexOf('editNode.addComponent(EditBox)'), true, 'form labels must exist before EditBox initialization')

process.stdout.write('merchant console static regression checks passed\n')
