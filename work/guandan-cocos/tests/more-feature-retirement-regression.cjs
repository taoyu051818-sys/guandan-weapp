const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const projectRoot = path.resolve(__dirname, '..')
const read = relativePath => fs.readFileSync(path.join(projectRoot, relativePath), 'utf8')
const frontPage = read('assets/scripts/scenes/FrontPageController.ts')
const playerCenterDomain = read('assets/scripts/scenes/front-pages/PlayerCenterPageDomain.ts')
const replaySpectatorDomain = read('assets/scripts/scenes/front-pages/ReplaySpectatorPageDomain.ts')
const settingsRulesDomain = read('assets/scripts/scenes/front-pages/SettingsRulesPageDomain.ts')
const merchantDomain = read('assets/scripts/scenes/front-pages/MerchantPageDomain.ts')
const lobbyDomain = read('assets/scripts/scenes/front-pages/LobbyPageDomain.ts')
const gameScene = read('assets/scripts/scenes/GameScene.ts')
const pageRouter = read('assets/scripts/scenes/PageRouter.ts')
const gameSession = read('assets/scripts/session/GameSession.ts')

const section = (start, end) => frontPage.slice(frontPage.indexOf(start), frontPage.indexOf(end))
const moreMenu = section('private showMoreMenu', 'public openEffectLabTable')
assert.match(moreMenu, /\['游戏设置', \(\) => this\.settingsRulesPage\.showSettings\(\)\]/)
assert.match(moreMenu, /延迟观战（实验）\\n一键进入30秒示例[\s\S]*this\.replaySpectatorPage\.showSpectatorDemo\(\)/)
assert.match(moreMenu, /快速开始·人机测试\\n最高难度 · 三位策略机器人[\s\S]*this\.startMasterBotTest\(\)/)
assert.match(moreMenu, /private startMasterBotTest[\s\S]*this\.host\.startMasterBotTest\(\)/, 'the release More menu must use the ordinary local-match host path instead of a DEV fixture')
assert.match(moreMenu, /listEffectLabFixtures\(\)\.length\) entries\.push\(\['牌桌特效测试'/, 'the EffectLab entry must remain behind the development fixture gate')
for (const retiredEntry of ['个人中心', '赛季任务', '我的牌谱', '双明牌教学', '本机数据', '商户后台']) {
  assert.equal(moreMenu.includes(retiredEntry), false, `${retiredEntry} must not return to the ordinary More menu`)
}

const profile = lobbyDomain.slice(lobbyDomain.indexOf('private renderLobbyPlayerProfile'), lobbyDomain.indexOf('private refreshLobbyDashboard'))
assert.match(profile, /LobbyPlayerProfileHitArea[\s\S]*dependencies\.showPlayerCenter/, 'the lobby profile lane must be the player-center entry')
const playerCenter = playerCenterDomain.slice(playerCenterDomain.indexOf('public async show'), playerCenterDomain.indexOf('private async showSeasonTasks'))
assert.match(playerCenter, /settle\(this\.dependencies\.gateways\.playerCenter\.getDashboard\(\)\)/)
assert.match(playerCenter, /settle\(this\.dependencies\.gateways\.wallet\.getWallet\(\)\)/)
assert.match(playerCenter, /dashboard\.user\.accountId/)
assert.match(playerCenter, /this\.dependencies\.wallet\.value\.points/)
assert.match(playerCenter, /dashboard\.rating\.comprehensiveScore/)
assert.match(playerCenter, /'赛季任务'[\s\S]*showSeasonTasks/)
assert.match(playerCenter, /'我的牌谱'[\s\S]*dependencies\.showReplayList/)
assert.match(playerCenter, /'返回大厅'[\s\S]*dependencies\.showMenu/)

const tasks = playerCenterDomain.slice(playerCenterDomain.indexOf('private async showSeasonTasks'), playerCenterDomain.indexOf('private isCurrent'))
assert.match(tasks, /this\.dependencies\.gateways\.configured && task\.completed && !task\.claimed/, 'only a configured platform may expose a claim action')
assert.match(tasks, /task\.completed \? '演示完成'/, 'development fixtures must not claim a reward is available')
assert.match(tasks, /!this\.dependencies\.gateways\.configured/, 'the claim method must reject direct development-mode calls')
assert.match(tasks, /'返回个人中心'[\s\S]*this\.show\(\)/)

const replayList = replaySpectatorDomain.slice(replaySpectatorDomain.indexOf('private async refreshReplayList'), replaySpectatorDomain.indexOf('private async refreshReplayDetail'))
assert.match(replayList, /开发模拟牌谱 · 不代表真实战绩/)
const replayRenderer = replaySpectatorDomain.slice(replaySpectatorDomain.indexOf('private renderReplayList'), replaySpectatorDomain.indexOf('private renderReplayDetail'))
assert.match(replayRenderer, /'返回个人中心'[\s\S]*dependencies\.showPlayerCenter/)
const replayDetail = replaySpectatorDomain.slice(replaySpectatorDomain.indexOf('private async refreshReplayDetail'), replaySpectatorDomain.indexOf('private async refreshSpectatorList'))
