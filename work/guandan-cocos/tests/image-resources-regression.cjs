const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const root = path.resolve(__dirname, '..')

async function run () {
  const { verifyImageResources } = await import('../scripts/image-resource-audit.mjs')
  const actual=verifyImageResources(root)
  assert.equal(actual.retired,8)
  assert.ok(actual.totalBytes<6*1024*1024)
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'art-source/image-resources.json')))
  const beach=manifest.images.find(i=>i.path.endsWith('/quick-start-beach.png'))
  assert.equal(beach.maxWidth,832);assert.equal(beach.maxHeight,176)
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'guandan-image-gate-'))
  try {
    fs.mkdirSync(path.join(dir,'assets'));fs.mkdirSync(path.join(dir,'art-source'))
    const image=fs.readFileSync(path.join(root,'assets/game-assets/ui/profiles/003.png'))
    fs.writeFileSync(path.join(dir,'assets/sample.png'),image)
    fs.writeFileSync(path.join(dir,'assets/sample.png.meta'),JSON.stringify({uuid:'test'}))
    fs.writeFileSync(path.join(dir,'consumer.ts'),"'sample/texture'")
    const fixture={maxTotalBytes:20000,retired:[],images:[{id:'sample',path:'assets/sample.png',usage:'test',lifetime:'page',sourceEvidence:'consumer.ts',maxWidth:4096,maxHeight:4096,maxBytes:20000,consumers:[{file:'consumer.ts',token:'sample/texture'}]}]}
    const write=()=>fs.writeFileSync(path.join(dir,'art-source/image-resources.json'),JSON.stringify(fixture))
    write();verifyImageResources(dir)
    fixture.images[0].maxBytes=1;write();assert.throws(()=>verifyImageResources(dir),/byte budget/)
    fixture.images[0].maxBytes=20000;fixture.images[0].maxWidth=1;write();assert.throws(()=>verifyImageResources(dir),/pixel budget/)
    fixture.images[0].maxWidth=4096;write()
    fs.writeFileSync(path.join(dir,'consumer.ts'),'retired');assert.throws(()=>verifyImageResources(dir),/consumer reference retired/)
    fs.writeFileSync(path.join(dir,'consumer.ts'),"'sample/texture'")
    fs.writeFileSync(path.join(dir,'assets/copy.png'),image);assert.throws(()=>verifyImageResources(dir),/reviewed inventory/)
    fixture.images.push({...fixture.images[0],id:'copy',path:'assets/copy.png'});write()
    assert.throws(()=>verifyImageResources(dir),/duplicate pixels/)
    fs.unlinkSync(path.join(dir,'assets/copy.png'));fixture.images.pop()
    fs.mkdirSync(path.join(dir,'assets/game-assets'))
    fs.renameSync(path.join(dir,'assets/sample.png'),path.join(dir,'assets/game-assets/sample.png'))
    fs.renameSync(path.join(dir,'assets/sample.png.meta'),path.join(dir,'assets/game-assets/sample.png.meta'))
    fixture.images[0].path='assets/game-assets/sample.png';write()
    const builtRoot=path.join(dir,'build'),native=path.join(builtRoot,'assets/game-assets/native/te/test.png')
    fs.mkdirSync(path.dirname(native),{recursive:true});fs.writeFileSync(native,image)
    verifyImageResources(dir,{buildRoot:builtRoot})
    // Simulate import encoding changes without changing image dimensions.
    const imported=Buffer.concat([image,Buffer.from('import metadata')])
    fs.writeFileSync(native,imported)
    assert.throws(()=>verifyImageResources(dir,{buildRoot:builtRoot}),/built image is stale/)
    fs.mkdirSync(path.join(dir,'library/te'),{recursive:true})
    fs.writeFileSync(path.join(dir,'library/te/test.png'),imported)
    fs.writeFileSync(path.join(dir,'assets/game-assets/sample.png.meta'),JSON.stringify({uuid:'test',userData:{fixAlphaTransparencyArtifacts:true}}))
    verifyImageResources(dir,{buildRoot:builtRoot})
    fs.writeFileSync(native,image)
    assert.throws(()=>verifyImageResources(dir,{buildRoot:builtRoot}),/built image is stale/)
  } finally {fs.rmSync(dir,{recursive:true,force:true})}
  console.log(`Image inventory: ${actual.count} images, ${actual.totalBytes} bytes; retirement, unknown files, dimensions, duplicates and reference gates passed`)
}
run().catch(error=>{console.error(error);process.exitCode=1})
