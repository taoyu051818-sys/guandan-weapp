assert.match(spectatorFeed, /session\.isDemo[\s\S]*公开牌桌[\s\S]*结束示例/)

const rulesDialog = settingsRulesDomain.slice(settingsRulesDomain.indexOf('public showRules'), settingsRulesDomain.indexOf('public showSettings'))
assert.match(lobbyDomain, /compactButton\(ui, '规则'[\s\S]*dependencies\.showRules/)
assert.doesNotMatch(frontPage, /教程|tutorial/i, 'the retired tutorial wording and route must not remain in the front-page runtime')
assert.match(rulesDialog, /openModal\('rules'\)/)
assert.match(rulesDialog, /RulesModalShade[\s\S]*BlockInputEvents/)
assert.match(rulesDialog, /RulesModal[\s\S]*BlockInputEvents/)
assert.match(rulesDialog, /RulesPrevious[\s\S]*上一页[\s\S]*RulesNext[\s\S]*下一页/)
assert.match(settingsRulesDomain, /dependencies\.router\.closeModal\(\)/)
assert.match(frontPage, /const reopenRules = this\.settingsRulesPage\.rulesVisible[\s\S]*if \(reopenRules\) this\.settingsRulesPage\.showRules\(\)/, 'viewport changes must preserve the open rules modal')
assert.match(lobbyDomain, /router\.current === 'menu' && !this\.dependencies\.rulesVisible\(\)\) this\.renderMenu\(\)/, 'late profile refreshes must not dismiss the rules modal')
for (const copy of ['基础与目标', '牌型与识别', '大小与压牌', '出牌与配合', '升级与胜负']) assert.match(settingsRulesDomain, new RegExp(copy))
assert.match(pageRouter, /openModal[\s\S]*closeModal[\s\S]*destroyModalRoot/)
assert.doesNotMatch(pageRouter, /'tutorial'/)

const settings = settingsRulesDomain.slice(settingsRulesDomain.indexOf('public showSettings'), settingsRulesDomain.indexOf('private closeRules'))
assert.doesNotMatch(settings, /视觉主题|visualTheme|切换视觉主题/, 'the unused visual-theme preference must not be exposed in Settings')
assert.match(gameSession, /visualTheme/, 'the persisted visual-theme field must remain readable for save compatibility')

for (const retiredRoute of ["'grouping'", "'stats'"]) assert.equal(pageRouter.includes(retiredRoute), false, `${retiredRoute} route must be retired`)
for (const retiredWire of ['GroupingController', 'groupingResult', 'beginGrouping', 'showGrouping', 'drawGrouping', 'enterRound', 'showStats']) {
  assert.equal(frontPage.includes(retiredWire), false, `${retiredWire} must be absent from FrontPageController`)
}
assert.doesNotMatch(gameScene, /GroupingController|public grouping:|this\.grouping/, 'GameScene must not recreate the retired draw-to-deal controller')
assert.equal(fs.existsSync(path.join(projectRoot, 'assets/scripts/game/GroupingController.ts')), false)
assert.equal(fs.existsSync(path.join(projectRoot, 'assets/scripts/game/GroupingController.ts.meta')), false)

assert.match(merchantDomain, /export class MerchantPageDomain/, 'merchant client code remains as an explicit migration boundary')
assert.doesNotMatch(frontPage, /showMerchantConsole|pendingMerchantAction/, 'merchant migration code must not leak into the ordinary front-page shell')
process.stdout.write('More feature retirement regression checks passed\n')
