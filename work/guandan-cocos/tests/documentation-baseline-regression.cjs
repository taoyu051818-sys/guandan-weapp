const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const app = path.resolve(__dirname, '..')
const read = name => fs.readFileSync(path.join(app, name), 'utf8')
const inventory = JSON.parse(execFileSync(process.execPath, ['scripts/audit-code-health.mjs', '--json'], { cwd: app, encoding: 'utf8' }))
const listed = read('docs/CODE_FILE_INVENTORY.md').split('\n')
  .filter(line => /^\| (?:shared-core\/src|work\/.*\/assets\/scripts|work\/.*\/server)\//.test(line))
  .map(line => line.split('|')[1].trim()).sort()
assert.deepEqual(listed, inventory.records.map(record => record.file).sort(), 'regenerate the file inventory when source paths change')
assert.match(read('docs/CURRENT_CAPABILITIES.md'), /不代表已上传微信、已部署服务器或通过真机验收/)
assert.doesNotMatch(read('README.md'), /赛事按钮目前只提示|旧赛事页面只保留|完整 Female and Male/)
const licenses = read('THIRD_PARTY.md')
assert.doesNotMatch(licenses, /\b25 reachable clips|\b2 clips, never imported|import-niuma-male-audio\.mjs/)
assert.match(licenses, /4 clips: deal, bomb, defeat, female single 5/)
assert.match(licenses, /22 clips, never imported/)
assert.match(licenses, /All quick-chat buttons, text\/broadcast logic and audio routes are retired/)
console.log(`Current documentation boundaries and ${listed.length} inventory paths verified; not a runtime or license-rights audit`)
