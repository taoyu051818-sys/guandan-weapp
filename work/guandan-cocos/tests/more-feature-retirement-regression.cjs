const spectatorList = replaySpectatorDomain.slice(replaySpectatorDomain.indexOf('private async refreshSpectatorList'), replaySpectatorDomain.indexOf('private renderSpectatorList'))
assert.match(spectatorList, /开发模拟观战/)
assert.match(replaySpectatorDomain, /延迟观战（实验）/)
assert.match(replaySpectatorDomain, /showSpectatorDemo[\s\S]*demo-live-match[\s\S]*spectatorDemoGateway/)
const spectatorFeed = replaySpectatorDomain.slice(replaySpectatorDomain.indexOf('private renderSpectatorFeed'), replaySpectatorDomain.indexOf('private renderReplayControls'))
